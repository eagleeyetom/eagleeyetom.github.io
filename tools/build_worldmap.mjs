// Builds the world map used on the online stage and on the ensemble pages.
//
//   npm i --no-save world-atlas@2 topojson-client topojson-simplify d3-geo world-countries
//   node tools/build_worldmap.mjs
//
// Natural Earth data (public domain) via world-atlas, in the Mercator projection of web maps
// (north is up and countries keep their familiar shape), cut to the latitudes 80°N to 56°S.
// Outputs:
//   public/assets/img/world-map.svg   all land in one path (the base of every map)
//   src/data/worldMap.ts              viewBox, projection constants and one path per country
//                                     (used to highlight the countries that take part)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import { presimplify, simplify, quantile } from 'topojson-simplify';
import { geoMercator, geoPath, geoBounds } from 'd3-geo';

const require = createRequire(import.meta.url);
const read = (name) => JSON.parse(readFileSync(require.resolve(`world-atlas/${name}`), 'utf8'));
const countriesList = require('world-countries');

const WIDTH = 1000;
const DIGITS = 1;
// Share of the most detailed 50m points that is kept (the rest is simplified away): enough for a
// map zoomed to a region, light enough to ship (about 100 KB for all land)
const KEEP = 0.2;

function load(name) {
  const topo = presimplify(read(name));
  return simplify(topo, quantile(topo, KEEP));
}
const countriesTopo = load('countries-50m.json');
const landTopo = load('land-50m.json');

// Antarctica takes a third of the map and has no ensembles: leave it out
const countries = feature(countriesTopo, countriesTopo.objects.countries).features.filter((f) => f.id !== '010');
const landGeometry = feature(landTopo, landTopo.objects.land).features[0].geometry;
const landPolygons = landGeometry.coordinates
  .map((coordinates) => ({ type: 'Polygon', coordinates }))
  .filter((polygon) => geoBounds(polygon)[1][1] > -60);
const land = { type: 'FeatureCollection', features: landPolygons.map((geometry) => ({ type: 'Feature', geometry })) };

const NORTH = 80;
const SOUTH = -56;
const projection = geoMercator().scale(WIDTH / (2 * Math.PI)).translate([WIDTH / 2, 0]);
const top = projection([0, NORTH])[1];
const bottom = projection([0, SOUTH])[1];
projection.translate([WIDTH / 2, -top]);
const HEIGHT = bottom - top;
projection.clipExtent([[0, 0], [WIDTH, HEIGHT]]);
const path = geoPath(projection).digits(DIGITS);
const viewBox = [0, 0, WIDTH, Math.round(HEIGHT)];

const landPath = land.features.map((f) => path(f)).filter(Boolean).join('');
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox.join(' ')}"><path fill="#cfc8c0" d="${landPath}"/></svg>\n`;
writeFileSync('public/assets/img/world-map.svg', svg);

const alpha2ByNumeric = new Map(countriesList.map((c) => [c.ccn3, c.cca2.toLowerCase()]));
const countryPaths = {};
const countryBoxes = {};
const [vx, vy, vw, vh] = viewBox;
for (const f of countries) {
  const code = alpha2ByNumeric.get(String(f.id).padStart(3, '0'));
  const d = path(f);
  if (!code || !d) continue;
  countryPaths[code] = d;

  // Bounding box of the country proper, in percent of the map: the polygons that are at least a
  // quarter the size of the biggest one, so far-away territories (French Guiana, Alaska) do not
  // stretch it. The ensemble pages zoom to this box plus its surroundings.
  const polygons = f.geometry.type === 'MultiPolygon'
    ? f.geometry.coordinates.map((coordinates) => ({ type: 'Polygon', coordinates }))
    : [f.geometry];
  const sized = polygons.map((geometry) => ({ geometry, area: path.area(geometry) }));
  const biggest = Math.max(...sized.map((p) => p.area));
  const boxes = sized.filter((p) => p.area >= biggest * 0.25).map((p) => path.bounds(p.geometry));
  const x0 = Math.min(...boxes.map((b) => b[0][0]));
  const y0 = Math.min(...boxes.map((b) => b[0][1]));
  const x1 = Math.max(...boxes.map((b) => b[1][0]));
  const y1 = Math.max(...boxes.map((b) => b[1][1]));
  countryBoxes[code] = [
    +(((x0 - vx) / vw) * 100).toFixed(2), +(((y0 - vy) / vh) * 100).toFixed(2),
    +(((x1 - vx) / vw) * 100).toFixed(2), +(((y1 - vy) / vh) * 100).toFixed(2),
  ];
}

const k = projection.scale();
const [tx, ty] = projection.translate();
const ts = `// Generated by tools/build_worldmap.mjs: do not edit by hand.
// Mercator projection, ${WIDTH} units wide, from ${NORTH}°N to ${-SOUTH}°S (no Antarctica).

export const worldMap = {
  viewBox: ${JSON.stringify(viewBox)} as [number, number, number, number],
  scale: ${k},
  translate: [${tx}, ${ty}] as [number, number],
} as const;

/** Position of a place on the map, in percent of the map's width and height. */
export function project(lon: number, lat: number): { x: number; y: number } {
  const lambda = (lon * Math.PI) / 180;
  const phi = (lat * Math.PI) / 180;
  const px = worldMap.scale * lambda + worldMap.translate[0];
  const py = worldMap.translate[1] - worldMap.scale * Math.log(Math.tan(Math.PI / 4 + phi / 2));
  const [vx, vy, vw, vh] = worldMap.viewBox;
  return { x: ((px - vx) / vw) * 100, y: ((py - vy) / vh) * 100 };
}

/** Bounding box [left, top, right, bottom] of each country, in percent of the map. */
export const countryBoxes: Record<string, [number, number, number, number]> = ${JSON.stringify(countryBoxes)};

/** One SVG path per country (ISO 3166-1 alpha-2, lower case), same coordinates as the viewBox. */
export const countryPaths: Record<string, string> = ${JSON.stringify(countryPaths)};
`;
writeFileSync('src/data/worldMap.ts', ts);

// Self-check: the formula above must land where d3 puts the point
const check = [['Tokyo', 139.69, 35.68], ['Cape Town', 18.42, -33.92], ['Buenos Aires', -58.38, -34.6], ['Gdańsk', 18.65, 54.35]];
for (const [name, lon, lat] of check) {
  const [px, py] = projection([lon, lat]);
  console.log(name.padEnd(13), 'd3:', (((px - vx) / vw) * 100).toFixed(2), (((py - vy) / vh) * 100).toFixed(2));
}
console.log('viewBox', viewBox.join(' '), '| land svg', Math.round(svg.length / 1024), 'KB | countries', Object.keys(countryPaths).length,
  '| worldMap.ts', Math.round(ts.length / 1024), 'KB');
